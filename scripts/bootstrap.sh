#!/usr/bin/env bash
# Generates .env with the two secrets docker compose requires.
# Idempotent-safe: refuses to overwrite an existing .env unless --force.
set -euo pipefail

cd "$(dirname "$0")/.."

FORCE=0
for arg in "$@"; do
  case "$arg" in
    --force) FORCE=1 ;;
    -h|--help)
      echo "Usage: scripts/bootstrap.sh [--force]"
      echo "Writes .env with fresh DTE_SECRETS_KEY (Fernet) and DTE_JWT_SECRET."
      exit 0
      ;;
    *) echo "unknown arg: $arg" >&2; exit 2 ;;
  esac
done

if [[ -f .env && $FORCE -eq 0 ]]; then
  echo ".env already exists — pass --force to overwrite." >&2
  exit 1
fi

need() { command -v "$1" >/dev/null 2>&1 || { echo "missing required tool: $1" >&2; exit 1; }; }
need python3
need docker

FERNET=$(python3 -c 'import base64, os; print(base64.urlsafe_b64encode(os.urandom(32)).decode())')
JWT=$(python3 -c 'import secrets; print(secrets.token_urlsafe(48))')

cat > .env <<EOF
# Generated by scripts/bootstrap.sh — rotate for production.
DTE_SECRETS_KEY=$FERNET
DTE_JWT_SECRET=$JWT
EOF

echo "wrote .env"
echo "next: docker compose up -d --build"
