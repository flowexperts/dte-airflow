"""One-time repoint: eval-demo invoices move from /tmp to a git-tracked path.

`generate_eval_demo_invoices.py` produces byte-different (but content-
equivalent) PDFs from the ones that used to live at
`/tmp/dte-samples/eval-demo/invoices` — a different PDF builder wrote the
originals, and there is no way to reproduce their exact bytes. Since
`doc_key = sha256(document bytes)`, every label and eval-set example keyed
against the old files needs to move to the new hash for the same invoice.

This script, run once against a live database:

1. Points the `demo_invoices` source's `bucket_url` at the new in-repo,
   container-mounted path.
2. Rewrites `eval_examples.doc_key` from each old hash to its replacement,
   for every eval set — not just the one this session happened to touch.

Idempotent: an old hash that's already been rewritten (or never existed)
matches zero rows and the UPDATE is a no-op.

Usage:
    cd backend
    DATABASE_URL=postgresql://dte:dte@localhost:5432/dte \
        uv run python scripts/repoint_eval_demo_invoices.py           # dry run
    DATABASE_URL=postgresql://dte:dte@localhost:5432/dte \
        uv run python scripts/repoint_eval_demo_invoices.py --write
"""
