async def main(write: bool) -> None:
    db_url = os.environ["DATABASE_URL"]
    if db_url.startswith("postgresql://"):
        db_url = db_url.replace("postgresql://", "postgresql+asyncpg://", 1)
    engine = create_async_engine(db_url)

    async with engine.begin() as conn:
        row = await conn.execute(
            text("select config->>'bucket_url' from sources where id = 'demo_invoices'")
        )
        current = row.scalar_one_or_none()
        print(f"demo_invoices.bucket_url is currently: {current!r}")
        if write and current == OLD_BUCKET_URL:
            await conn.execute(
                text(
                    "update sources set config = jsonb_set(config, '{bucket_url}', :new) "
                    "where id = 'demo_invoices'"
                ),
                {"new": f'"{NEW_BUCKET_URL}"'},
            )
            print(f"  -> rewritten to {NEW_BUCKET_URL!r}")

        for old_hash, new_hash in HASH_MAP:
            row = await conn.execute(
                text("select eval_set_id from eval_examples where doc_key = :old"),
                {"old": old_hash},
            )
            sets = [r[0] for r in row.fetchall()]
            if not sets:
                continue
            print(f"{old_hash[:12]} -> {new_hash[:12]}: eval sets {sets}")
            if write:
                await conn.execute(
                    text(
                        "update eval_examples set doc_key = :new "
                        "where doc_key = :old"
                    ),
                    {"old": old_hash, "new": new_hash},
                )

    await engine.dispose()
    if not write:
        print("\nDry run — pass --write to apply.")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    asyncio.run(main(args.write))
