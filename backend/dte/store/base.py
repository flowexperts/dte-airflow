from typing import TYPE_CHECKING, Protocol, runtime_checkable

if TYPE_CHECKING:
    from dte.models.pipeline import (
        Connection,
        ConnectionBase,
        Destination,
        DestinationBase,
        LookupTable,
        LookupTableBase,
        Pipeline,
        PipelineRevision,
        PipelineRevisionBase,
        Source,
        SourceBase,
    )
    from dte.models.user import Role, User, UserBase


@runtime_checkable
class PipelineStore(Protocol):
    async def get(self, id: str) -> "Pipeline | None": ...
    async def save(self, pipeline: "Pipeline") -> None: ...
    async def list(self, limit: int = 50, offset: int = 0) -> "list[Pipeline]": ...
    async def delete(self, id: str) -> bool: ...


@runtime_checkable
class RunStore(Protocol):
    async def get(self, id: str) -> dict | None: ...
    async def create(self, pipeline_id: str, revision_id: str | None = None) -> str: ...
    async def update(self, id: str, **fields) -> None: ...
    async def list_for_pipeline(self, pipeline_id: str, limit: int = 50) -> list[dict]: ...
    async def delete_for_pipeline(self, pipeline_id: str) -> int: ...


@runtime_checkable
class PipelineRevisionStore(Protocol):
    """Append-only history of pipeline edits. `save` writes a new immutable
    row per call — no upsert. `latest_for_pipeline` returns the most-recent
    revision id (used to pin runs at trigger time)."""

    async def save(self, revision: "PipelineRevisionBase | PipelineRevision") -> None: ...
    async def get(self, id: str) -> "PipelineRevision | None": ...
    async def list_for_pipeline(
        self, pipeline_id: str, limit: int = 100
    ) -> "list[PipelineRevision]": ...
    async def latest_for_pipeline(self, pipeline_id: str) -> "PipelineRevision | None": ...


@runtime_checkable
class RunEventStore(Protocol):
    """Per-step events emitted during pipeline runs.

    `record` inserts or updates the terminal row (started → completed/failed)
    keyed on (run_id, step_index). `list_for_run` returns them in step order
    for the /api/runs/{id}/events endpoint that feeds the Timeline UI.
    """

    async def record(
        self,
        run_id: str,
        step_index: int,
        op: str,
        status: str,
        message: str | None = None,
    ) -> None: ...
    async def list_for_run(self, run_id: str) -> list[dict]: ...


